def load_glb_json(path: Path) -> dict[str, Any]:
    with path.open("rb") as file:
        header = file.read(12)
        if len(header) != 12:
            raise RuntimeError(f"Invalid GLB header: {path}")
        magic, version, _length = struct.unpack("<III", header)
        if magic != 0x46546C67 or version != 2:
            raise RuntimeError(f"Unsupported GLB container: {path}")

        chunk_header = file.read(8)
        if len(chunk_header) != 8:
            raise RuntimeError(f"Missing GLB JSON chunk: {path}")
        chunk_length, chunk_type = struct.unpack("<II", chunk_header)
        if chunk_type != 0x4E4F534A:
            raise RuntimeError(f"First GLB chunk is not JSON: {path}")
        return json.loads(file.read(chunk_length).decode("utf-8").rstrip("\x00 "))


def number_literal(value: float) -> str:
    rounded = 0.0 if abs(value) < 0.000001 else value
    return f"{rounded:.6f}".rstrip("0").rstrip(".") or "0"


def collect_scene_stats(gltf: dict[str, Any]) -> dict[str, int]:
    accessors = gltf.get("accessors", [])
    meshes = gltf.get("meshes", [])
    nodes = gltf.get("nodes", [])
    scene = gltf["scenes"][gltf.get("scene", 0)]
    stats = {
        "parts": 0,
        "vertices": 0,
        "indices": 0,
        "skinnedParts": 0,
    }

    def visit_node(node_index: int) -> None:
        node = nodes[node_index]
        mesh_index = node.get("mesh")
        if mesh_index is not None:
            mesh = meshes[int(mesh_index)]
            for primitive in mesh.get("primitives", []):
                if primitive.get("mode", 4) != 4:
                    continue
                attributes = primitive.get("attributes", {})
                position_accessor_index = attributes.get("POSITION")
                if position_accessor_index is None:
                    continue
                vertex_count = int(accessors[int(position_accessor_index)]["count"])
                index_accessor_index = primitive.get("indices")
                index_count = (
                    int(accessors[int(index_accessor_index)]["count"])
                    if index_accessor_index is not None
                    else vertex_count
                )
                stats["parts"] += 1
                stats["vertices"] += vertex_count
                stats["indices"] += index_count
                if node.get("skin") is not None and ("JOINTS_0" in attributes or "WEIGHTS_0" in attributes):
                    stats["skinnedParts"] += 1

        for child_index in node.get("children", []):
            visit_node(int(child_index))

    for root_node_index in scene["nodes"]:
        visit_node(int(root_node_index))

    return stats


