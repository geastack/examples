def main() -> None:
    gltf = load_glb_json(ORIGINAL_GLB)
    stats = collect_scene_stats(gltf)
    if stats["parts"] == 0:
        raise RuntimeError("No Littlest Tokyo mesh primitives were found")

    write_generated_ts(stats)
    write_official_html()

    print("Generated Three Littlest Tokyo GLB reference")
    print(
        f"parts={stats['parts']} vertices={stats['vertices']} "
        f"indices={stats['indices']} skinnedParts={stats['skinnedParts']}"
    )
    print(GENERATED_TS_PATH)
    print(OFFICIAL_HTML_PATH)
    print(ORIGINAL_GLB)


if __name__ == "__main__":
    main()
